# Exemplo de código sequencial e repetitivo (sem uso de laços de repetição como 'for' ou 'while')

# Solicita a entrada do usuário e converte para número inteiro
a = int(input("Informe um número inteiro: "))
# Imprime o valor inicial fornecido
print(a)

# Incrementa a variável 'a' em 1 e imprime o novo valor (código repetitivo)
a += 1
print(a)

# Incrementa novamente a variável 'a' em 1 e imprime o novo valor (código repetitivo)
a += 1
print(a)
