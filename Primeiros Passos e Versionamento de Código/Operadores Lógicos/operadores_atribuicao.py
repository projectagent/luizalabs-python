# Atribuição Simples
saldo = 450
print(saldo)

# Atribuição com Adição
saldo += 500
print(saldo)

# Atribuição com Subtração
saldo -= 200
print(saldo)

# Atribuição com Multiplicação
saldo *= 2
print(saldo)

# Atribuição com Divisão
saldo //= 4
print(saldo)

saldo /= 2
print(saldo)

# Atribuição com Módulo
saldo %= 3
print(saldo)

# Atribuição com Exponenciação
saldo **= 10
print(saldo)